#!/usr/bin/env python3
"""Bake Edit's shared 6x11 bitmap font without enabling MicroFont hex at runtime.

Canonical mask-first MicroFont records remain the only edited glyph source.
The checked-in Rust and OpenCL tables have identical Unicode-sorted indices.
Missing lowercase-composition masks reuse the canonical bitmap accent and body
fragments of existing members of the same composition families.
"""

