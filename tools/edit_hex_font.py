SOURCE = ROOT / "vendor/microfont/data/line-v1"
RUST = ROOT / "src/r/services/shell3_hex_font.generated.rs"
OPENCL = ROOT / "crates/trueos-shader/gpgpu/kernels/edit_life_hex_font.generated.h"
BODY_BITS = 6 * 7
BODY_MASK = (1 << BODY_BITS) - 1
