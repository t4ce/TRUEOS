def source_masks(source: Path = SOURCE) -> tuple[list[tuple[int, int]], str, list[int]]:
    masks = {}
    compositions = []
    digest = hashlib.sha256()
    for path in sorted(source.rglob("*.bin")):
        data = path.read_bytes()
        digest.update(path.relative_to(source).as_posix().encode() + b"\0" + data)
        if len(data) < 20 or data[18:20] != b"\0\0" or data[16] & ~1:
            raise ValueError(f"Invalid mask-first font record: {path}")
        mask = int.from_bytes(data[:16], "little")
        if mask >> 66 or (not data[16] and mask):
            raise ValueError(f"Invalid 66-bit font mask: {path}")
        if not path.stem.startswith("u"):
            continue
        codepoint = int(path.stem[1:], 16)
        if codepoint > 0x10FFFF or 0xD800 <= codepoint <= 0xDFFF:
            raise ValueError(f"Invalid Unicode glyph: {path}")
        if data[16] & 1:
            if codepoint in masks:
                raise ValueError(f"Duplicate font glyph: {path}")
            masks[codepoint] = mask
        if data[17] == 4:
            if len(data) != 29:
                raise ValueError(f"Invalid lowercase composition: {path}")
            base, topper, omit_dot = struct.unpack("<IIB", data[20:])
            compositions.append((codepoint, base, topper, omit_dot))

    # Every existing accented bitmap puts its accent in rows 0..3 and its
    # lowercase body in rows 4..10. Assert the canonical family members agree
    # before filling the ten raster-only combinations from those same pixels.
    accents = {}
    bodies = {}
    for codepoint, base, topper, omit_dot in compositions:
        if codepoint not in masks or not topper:
            continue
        for fragments, key, fragment in (
            (accents, topper, masks[codepoint] & ~BODY_MASK),
            (bodies, (base, omit_dot), masks[codepoint] & BODY_MASK),
        ):
            if key in fragments and fragments[key] != fragment:
                raise ValueError(f"Inconsistent canonical bitmap composition U+{codepoint:04X}")
            fragments[key] = fragment
    composed = []
    for codepoint, base, topper, omit_dot in compositions:
        if codepoint in masks:
            continue
        if topper not in accents or (base, omit_dot) not in bodies:
            raise ValueError(f"No canonical bitmap fragments for U+{codepoint:04X}")
        masks[codepoint] = accents[topper] | bodies[base, omit_dot]
        composed.append(codepoint)
    if masks.get(0x20) != 0 or not masks.get(ord("?")):
        raise ValueError("Font needs a blank space and a visible question-mark fallback")
    return sorted(masks.items()), digest.hexdigest(), sorted(composed)


def generated() -> dict[Path, str]:
    masks, digest, composed = source_masks()
    ids = {codepoint: index for index, (codepoint, _) in enumerate(masks)}
    comment = "// " + LICENSE.replace("\n", "\n// ") + "\n"
    provenance = ("// @generated by tools/edit_hex_font.py; do not edit.\n"
        + comment + f"// Canonical source SHA-256: {digest}\n"
        + "// Composed from canonical bitmap fragments: "
        + ", ".join(f"U+{codepoint:04X}" for codepoint in composed) + "\n"
        + "// Full 66-bit masks, little-endian u32 words; top-left bit 65.\n")
    rust = provenance
    rust += f"pub(crate) const GLYPH_COUNT: usize = {len(masks)};\n"
    rust += f"pub(crate) const SPACE_GLYPH: u32 = {ids[0x20]};\n"
    rust += f"pub(crate) const FALLBACK_GLYPH: u32 = {ids[ord('?')]};\n"
    rust += "pub(crate) const CODEPOINTS: [u32; GLYPH_COUNT] = [\n"
    for start in range(0, len(masks), 12):
        rust += "    " + ", ".join(f"0x{cp:04x}" for cp, _ in masks[start:start + 12]) + ",\n"
    rust += "];\npub(crate) const MASKS: [[u32; 4]; GLYPH_COUNT] = [\n"
    opencl = provenance + "#ifndef TRUEOS_EDIT_HEX_FONT_GENERATED_H\n#define TRUEOS_EDIT_HEX_FONT_GENERATED_H\n"
    opencl += f"#define EDIT_HEX_GLYPH_COUNT {len(masks)}u\n"
    opencl += f"#define EDIT_HEX_SPACE_GLYPH {ids[0x20]}u\n"
    opencl += f"#define EDIT_HEX_FALLBACK_GLYPH {ids[ord('?')]}u\n"
    for codepoint, mask in masks:
        words = [(mask >> (32 * word)) & 0xFFFFFFFF for word in range(4)]
        rust += "    [" + ", ".join(f"0x{word:08x}" for word in words) + f"], // U+{codepoint:04X}\n"
    rust += "];\n"
    opencl += """
// This explicit resource is uploaded once from Rust MASKS. An OpenCL program-
// scope constant array would add an implicit IGC constant binding to the ABI.
static inline uint trueos_edit_hex_coverage(__global const uint4 *masks, uint glyph_index, uint x, uint y) {
    if (x >= 6u || y >= 11u) return 0u;
    if (glyph_index >= EDIT_HEX_GLYPH_COUNT) glyph_index = EDIT_HEX_FALLBACK_GLYPH;
    uint bit = 65u - y * 6u - x;
    uint4 words = masks[glyph_index];
    return ((words[bit >> 5] >> (bit & 31u)) & 1u) * 255u;
}

#endif
"""
    return {RUST: rust, OPENCL: opencl}


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="Fail if generated data is stale")
    args = parser.parse_args()
    for path, text in generated().items():
        if args.check:
            if not path.is_file() or path.read_text() != text:
                raise SystemExit(f"Stale generated hex font: {path.relative_to(ROOT)}")
        else:
            path.write_text(text)
        print(("checked " if args.check else "generated ") + str(path.relative_to(ROOT)))


if __name__ == "__main__":
    main()
