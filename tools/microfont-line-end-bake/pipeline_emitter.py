"""Emit reusable native VS/PS pipeline declarations for Microfont bakes."""
from pathlib import Path
import struct

GENERATED: Path

def emit_rust(vs: bytes, ps: bytes, state: dict[str, int], ps_state: dict[str, int]) -> None:
    def words(name: str, binary: bytes) -> str:
        values = struct.unpack(f"<{len(binary) // 4}I", binary)
        rows = ["    " + ", ".join(f"0x{word:08X}" for word in values[index:index + 8]) + ","
                for index in range(0, len(values), 8)]
        return f"static {name}: [u32; {len(values)}] = [\n" + "\n".join(rows) + "\n];\n"

    generated = "// @generated by tools/microfont-line-end-bake/bake.py; ADL-S. Compile-only.\n" +         "use super::{DispatchMode, ShaderKernelMetadata, TrianglePipeline, TrianglePixelShader, TrianglePixelShaderMetadata, TriangleVertexShader, TriangleVertexShaderMetadata};\n"
    generated += words("MICROFONT_LINE_END_VS_CODE", vs) + "\n"
    generated += words("MICROFONT_LINE_END_PS_SIMD16_CODE", ps) + "\n"
    generated += f'''static MICROFONT_LINE_END_TEXTURE_PIPELINE: TrianglePipeline = TrianglePipeline {{
    vs: TriangleVertexShader {{
        code: &MICROFONT_LINE_END_VS_CODE,
        meta: TriangleVertexShaderMetadata {{
            kernel: ShaderKernelMetadata {{
                code_offset_bytes: 0,
                code_size_bytes: {len(vs)},
                code_alignment_bytes: 64,
                ksp_offset_bytes: 0,
                dispatch_mode: DispatchMode::Simd8,
                grf_start_register: {state["dispatch_grf_start"]},
                grf_used: 128,
                push_constant_bytes: 0,
                binding_table_entry_count: {state["binding_table_entries"]},
                sampler_count: 0,
            }},
            max_threads: {state["max_threads"]},
            urb_entry_output_length: {state["urb_entry_64b"]},
        }},
    }},
    ps: TrianglePixelShader {{
        code: &MICROFONT_LINE_END_PS_SIMD16_CODE,
        meta: TrianglePixelShaderMetadata {{
            kernel: ShaderKernelMetadata {{
                code_offset_bytes: {(len(vs) + 63) & ~63},
                code_size_bytes: {len(ps)},
                code_alignment_bytes: 64,
                ksp_offset_bytes: 0,
                dispatch_mode: DispatchMode::Simd16,
                grf_start_register: {ps_state["grf_start16"]},
                grf_used: 128,
                push_constant_bytes: 0,
                binding_table_entry_count: {ps_state["binding_table_entries"]},
                sampler_count: {ps_state["sampler_count"]},
            }},
            num_varying_inputs: {ps_state["num_varying_inputs"]},
            uses_vmask: {str(bool(ps_state["uses_vmask"])).lower()},
            computed_stencil: false,
            persample_dispatch: false,
            computed_depth_mode: {ps_state["computed_depth_mode"]},
            flat_inputs: 0,
        }},
    }},
}};

pub(crate) fn microfont_line_end_pipeline() -> &'static TrianglePipeline {{
    &MICROFONT_LINE_END_TEXTURE_PIPELINE
}}

'''
    GENERATED.write_text(generated)

